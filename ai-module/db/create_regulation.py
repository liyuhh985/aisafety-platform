"""建法规库表 + 种子数据。"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import pymysql
from db_config import DB_CONFIG


def run():
    conn = pymysql.connect(**DB_CONFIG)
    try:
        with conn.cursor() as cur:
            # 建表
            cur.execute("SHOW TABLES LIKE 'tb_regulation'")
            if cur.fetchone():
                print("tb_regulation 已存在")
                cur.execute("SELECT COUNT(*) FROM tb_regulation")
                count = cur.fetchone()[0]
                print(f"  已有 {count} 条记录")
                return

            cur.execute("""
                CREATE TABLE tb_regulation (
                    id          BIGINT AUTO_INCREMENT PRIMARY KEY,
                    category    VARCHAR(50)  NOT NULL COMMENT '对应隐患类别',
                    law_name    VARCHAR(200) NOT NULL COMMENT '法规名称',
                    article     VARCHAR(50)  NOT NULL COMMENT '条款号',
                    content     TEXT         NOT NULL COMMENT '条款原文',
                    keywords    VARCHAR(200) DEFAULT '' COMMENT '搜索关键词',
                    penalty     VARCHAR(500) DEFAULT '' COMMENT '处罚措施',
                    source_url  VARCHAR(500) DEFAULT '' COMMENT '来源',
                    create_time DATETIME     DEFAULT CURRENT_TIMESTAMP,
                    INDEX idx_category (category),
                    INDEX idx_keywords (keywords)
                ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='安全隐患法规库'
            """)
            print("tb_regulation 表创建成功")

            # 种子数据
            sql = """INSERT INTO tb_regulation
                (category, law_name, article, content, keywords, penalty, source_url) VALUES
                (%s, %s, %s, %s, %s, %s, %s)"""
            cur.executemany(sql, SEED_DATA)
            print(f"插入 {len(SEED_DATA)} 条法规")

        conn.commit()
        print("Done.")
    finally:
        conn.close()


