def run():
    conn = pymysql.connect(**DB_CONFIG)
    try:
        with conn.cursor() as cur:
            # ---- 法规 ----
            cur.execute("SELECT category, law_name, article FROM tb_regulation")
            existing_reg = set(cur.fetchall())
            new_reg = [r for r in REGULATIONS if (r[0], r[1], r[2]) not in existing_reg]
            if new_reg:
                sql = ("INSERT INTO tb_regulation "
                       "(category, law_name, article, content, keywords, penalty, source_url) "
                       "VALUES (%s,%s,%s,%s,%s,%s,%s)")
                cur.executemany(sql, new_reg)
                print(f"[法规] 插入 {len(new_reg)} 条")
            else:
                print("[法规] 无新增（均已存在）")

            # ---- 案例 ----
            cur.execute("SELECT title FROM tb_hazard_case")
            existing_case_titles = {row[0] for row in cur.fetchall()}
            new_case = [c for c in CASES if c[1] not in existing_case_titles]
            if new_case:
                sql = ("INSERT INTO tb_hazard_case "
                       "(category, title, description, severity, city, district, occurrence_date, "
                       "casualties, cause, rectification, regulation_ref, source_url, verdict) "
                       "VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)")
                cur.executemany(sql, new_case)
                print(f"[案例] 插入 {len(new_case)} 条")
            else:
                print("[案例] 无新增（均已存在）")

        conn.commit()

        # 汇总
        with conn.cursor() as cur:
            cur.execute("SELECT category, COUNT(*) FROM tb_regulation WHERE category IN ('占道','井盖/道路','消防通道','施工') GROUP BY category")
            print("法规库 4 类分布:")
            for r in cur.fetchall():
                print("   ", r[0], r[1])
            cur.execute("SELECT category, COUNT(*) FROM tb_hazard_case WHERE category IN ('占道','井盖/道路','消防通道','施工') GROUP BY category")
            print("案例库 4 类分布:")
            for r in cur.fetchall():
                print("   ", r[0], r[1])
    finally:
        conn.close()


if __name__ == "__main__":
    run()

