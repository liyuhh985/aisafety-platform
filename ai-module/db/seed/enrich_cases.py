def enrich():
    conn = pymysql.connect(**DB_CONFIG)
    try:
        with conn.cursor() as cur:
            updated = 0
            for case in ENRICHED:
                cur.execute(
                    "SELECT id, title FROM tb_hazard_case WHERE title LIKE %s",
                    (case["title_like"],),
                )
                row = cur.fetchone()
                if not row:
                    print(f"[SKIP] 未找到: {case['title_like']}")
                    continue
                case_id, title = row
                cur.execute(
                    "UPDATE tb_hazard_case SET description=%s, cause=%s, "
                    "rectification=%s, regulation_ref=%s, verdict=%s "
                    "WHERE id=%s",
                    (
                        case["description"],
                        case["cause"],
                        case["rectification"],
                        case["regulation_ref"],
                        case["verdict"],
                        case_id,
                    ),
                )
                print(f"[OK] 已更新: {title[:50]}...")
                updated += 1
            conn.commit()
            print(f"\n共更新 {updated} 条案例。")
    finally:
        conn.close()


