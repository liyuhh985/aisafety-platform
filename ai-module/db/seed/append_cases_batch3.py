def run():
    conn = pymysql.connect(**DB_CONFIG)
    try:
        with conn.cursor() as cur:
            cur.execute("SELECT title FROM tb_hazard_case")
            existing = {r[0] for r in cur.fetchall()}
            new = [c for c in CASES if c[1] not in existing]
            if new:
                sql = ("INSERT INTO tb_hazard_case "
                       "(category, title, description, severity, city, district, occurrence_date, "
                       "casualties, cause, rectification, regulation_ref, source_url, verdict) "
                       "VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)")
                cur.executemany(sql, new)
                print(f"[批次3] 插入 {len(new)} 条")
            else:
                print("[批次3] 无新增")
        conn.commit()
        with conn.cursor() as cur:
            cur.execute("SELECT category, COUNT(*) FROM tb_hazard_case WHERE category IN ('占道','井盖/道路','消防通道','施工') GROUP BY category ORDER BY category")
            for r in cur.fetchall():
                print("   ", r[0], "=", r[1])
    finally:
        conn.close()


if __name__ == "__main__":
    run()
